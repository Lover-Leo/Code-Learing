#include <iostream>
/*# P1075 [NOIP 2012 普及组] 质因数分解

## 题目描述

已知正整数 $n$ 是两个不同的质数的乘积，试求出两者中较大的那个质数。

## 输入格式

输入一个正整数 $n$。

## 输出格式

输出一个正整数 $p$，即较大的那个质数。

## 输入输出样例 #1

### 输入 #1

```
21
```

### 输出 #1

```
7
```*/
int main() {
    int n;
    std::cin >> n;

    for (int i = 2; i <= n / i; i++) {
        if (n % i == 0) {
            std::cout << n / i << '\n';
            return 0;
        }
    }

    return 0;
}
